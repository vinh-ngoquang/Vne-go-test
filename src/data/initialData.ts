// Function to parse numbers with commas like "19,268" or "2,002,024"
export function cleanNumber(val: string | undefined): number {
  if (!val) return 0;
  const cleaned = val.replace(/["',]/g, '').trim();
  const num = parseFloat(cleaned);
  return isNaN(num) ? 0 : num;
}

// Split CSV taking into account quotes
export function parseCSV(csvText: string): RawRecord[] {
  const lines = csvText.trim().split(/\r?\n/);
  if (lines.length <= 1) return [];

  const headers = lines[0].split(',').map(h => h.trim());
  const records: RawRecord[] = [];

  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    // Tokenize line with quoted values
    const values: string[] = [];
    let insideQuotes = false;
    let currentVal = '';

    for (let c = 0; c < line.length; c++) {
      const char = line[c];
      if (char === '"') {
        insideQuotes = !insideQuotes;
      } else if (char === ',' && !insideQuotes) {
        values.push(currentVal.trim());
        currentVal = '';
      } else {
        currentVal += char;
      }
    }
    values.push(currentVal.trim());

    if (values.length < headers.length) {
      // pad with empty strings if needed
      while (values.length < headers.length) values.push('');
    }

    const rowObj: Record<string, string> = {};
    headers.forEach((h, idx) => {
      rowObj[h] = values[idx] ?? '';
    });

    const catename = rowObj['Catename']?.replace(/"/g, '').trim() || 'Khác / Trang chung';

    records.push({
      date_days: rowObj['date_days'] || '',
      type_folder: rowObj['type_folder'] || '',
      users: cleanNumber(rowObj['users']),
      vne_user: cleanNumber(rowObj['vne_user']),
      pageview: cleanNumber(rowObj['pageview']),
      E_Direct: cleanNumber(rowObj['E_Direct']),
      E_Referrer: cleanNumber(rowObj['E_Referrer']),
      E_Search: cleanNumber(rowObj['E_Search']),
      E_Social: cleanNumber(rowObj['E_Social']),
      I_Detail: cleanNumber(rowObj['I_Detail']),
      I_Folder: cleanNumber(rowObj['I_Folder']),
      I_Home: cleanNumber(rowObj['I_Home']),
      I_Tag: cleanNumber(rowObj['I_Tag']),
      I_Topic: cleanNumber(rowObj['I_Topic']),
      I_24h: cleanNumber(rowObj['I_24h']),
      I_Other: cleanNumber(rowObj['I_Other']),
      session: cleanNumber(rowObj['session']),
      folder_ids: rowObj['folder_ids'] || '',
      MAU: cleanNumber(rowObj['MAU']),
      Catename: catename,
      join: rowObj['join'] || '',
    });
  }

  return records;
}

